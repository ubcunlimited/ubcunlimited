// Extract slug + name pairs by scanning for consecutive slug/name fields in TypeScript objects.
// The structure in utahLocations.ts is always: slug: "...", \n  name: "..."
function extractSlugNamePairs(src) {
  const pairs = [];
  // Match slug field followed (within ~200 chars) by name field
  const re = /slug:\s*['"`]([\w-]+)['"`][\s\S]{0,200}?name:\s*['"`]([^'"`\n]+)['"`]/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    pairs.push({ slug: m[1], name: m[2] });
  }
  return pairs;
}

// Extract slugs using regex
function extractSlugs(src) {
  return extractSlugNamePairs(src).map(p => p.slug);
}

// Extract href + label pairs from config
function extractHrefLabelPairs(src) {
  const pairs = [];
  const re = /href:\s*['"`](\/[^'"`]+)['"`][^{}]*label:\s*['"`]([^'"`]+)['"`]|label:\s*['"`]([^'"`]+)['"`][^{}]*href:\s*['"`](\/[^'"`]+)['"`]/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    const href = m[1] || m[4];
    const label = m[2] || m[3];
    if (href && label) pairs.push({ href, label });
  }
  return pairs;
}

// Extract blog titles
function extractBlogTitles(src) {
  const pairs = [];
  const re = /slug:\s*['"`]([\w-]+)['"`][\s\S]*?title:\s*['"`]([^'"`]+)['"`]/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    pairs.push({ slug: m[1], title: m[2] });
  }
  return pairs;
}

const allSlugs = extractSlugs(locationsSrc);
const countySlugs = allSlugs.slice(0, 29);
const citySlugs = allSlugs.slice(29); // 134 cities

const countyPairs = extractSlugNamePairs(locationsSrc).slice(0, 29);
const cityPairs = extractSlugNamePairs(locationsSrc).slice(29);

const navPairs = extractHrefLabelPairs(configSrc);
const solutionPairs = navPairs.filter(p => p.href.startsWith('/solutions/'));
const industryPairs = navPairs.filter(p => p.href.startsWith('/industries/'));

const blogPairs = extractBlogTitles(blogSrc);

// ── 2. Build the scaffold HTML ─────────────────────────────────────────────

function li(href, label) {
  return `          <li><a href="${href}">${label}</a></li>`;
}

const solutionLinks = solutionPairs.map(p => li(p.href, p.label)).join('\n');
const industryLinks = industryPairs.map(p => li(p.href, p.label)).join('\n');
const blogLinks = blogPairs.map(p => li(`/blog/${p.slug}`, p.title || p.slug)).join('\n');

// County links — use name from pairs if available, else format slug.
// Note: county names in utahLocations.ts already include "County" (e.g. "Salt Lake County")
const countyLinks = countyPairs.map(p => {
  const name = p.name || p.slug.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
  return li(`/counties/${p.slug}`, name);
}).join('\n');

// City links — use cityPairs directly (slug + name already paired correctly)
const cityLinks = cityPairs.map(p => {
  const name = p.name || p.slug.replace(/-/g, ' ').replace(/\b\w/g, c => c.toUpperCase());
  return li(`/cities/${p.slug}`, name);
}).join('\n');

