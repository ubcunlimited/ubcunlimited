const indexPath = path.join(ROOT, 'client/index.html');
let html = fs.readFileSync(indexPath, 'utf8');

// Replace the existing static-a11y-scaffold block (from the opening comment or div to the closing </div>)
const scaffoldStart = /    <!-- Static crawler scaffold[\s\S]*?<div id="static-a11y-scaffold"[\s\S]*?<\/div>/;
const legacyStart = /    <!-- Static accessibility scaffold[\s\S]*?<div id="static-a11y-scaffold"[\s\S]*?<\/div>/;

